const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const source = fs.readFileSync(path.join(__dirname, '../desktop-ui/src/archivePresentation.ts'), 'utf8');
const context = { exports: {} };
vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, context);
const present = context.exports.archivePresentation;
assert.equal(present({ upload_status: 'success', archive_detail: { upload_evidence: 'history', cleanup_enabled: false } }).cloud, '曾上传，待复核');
assert.equal(present({ upload_status: 'success', archive_detail: { upload_evidence: 'history', cleanup_enabled: false } }).local, '已保留，等待归档复核');
assert.equal(present({ upload_status: 'success', archive_detail: { upload_evidence: 'task' } }).cloud, '有上传成功记录');
assert.equal(present({ upload_status: 'success', archive_detail: { remote_checked_at: 1 } }).color, 'green');
assert.equal(present({ upload_status: 'success', archive_detail: { remote_checked_at: 1, cleanup_error: 'missing' } }).color, 'orange');
assert.equal(present({ archive_detail: { cleanup_due_at: 10 } }, 20).local, '已到清理时间，等待处理');
assert.match(present({ archive_detail: { cleanup_due_at: 30 } }, 20).local, /^保留至/);
assert.equal(present({ archive_detail: { cleanup_enabled: false, cleanup_due_at: 10 } }, 20).local, '已保留，尚未满足自动清理条件');
assert.equal(present({ upload_status: 'failed' }).cloud, '上传失败');
console.log('Archive presentation: 9 assertions passed');
